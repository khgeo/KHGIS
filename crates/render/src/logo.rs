/// An ellipse centred on the globe, as four cubic segments: `rx` of `R` is the globe's edge,
/// narrower values are the meridians drawn across it.
fn ellipse(rx: f32, ry: f32) -> Option<tiny_skia::Path> {
    let (kx, ky) = (rx * K, ry * K);
    let mut pb = PathBuilder::new();
    pb.move_to(C, C - ry);
    pb.cubic_to(C + kx, C - ry, C + rx, C - ky, C + rx, C);
    pb.cubic_to(C + rx, C + ky, C + kx, C + ry, C, C + ry);
    pb.cubic_to(C - kx, C + ry, C - rx, C + ky, C - rx, C);
    pb.cubic_to(C - rx, C - ky, C - kx, C - ry, C, C - ry);
    pb.close();
    pb.finish()
}

fn polyline(pts: &[(f32, f32)]) -> Option<tiny_skia::Path> {
    let mut pb = PathBuilder::new();
    let (x, y) = *pts.first()?;
    pb.move_to(x, y);
    for (x, y) in &pts[1..] {
        pb.line_to(*x, *y);
    }
    pb.finish()
}

/// Replays `RING_TEXT` into a path. Unknown input cannot reach here (the table is a constant),
/// so a malformed tail simply ends the path.
fn ring_text() -> Option<tiny_skia::Path> {
    let mut pb = PathBuilder::new();
    let t = &RING_TEXT;
    let mut i = 0usize;
    while i < t.len() {
        match t[i] as u8 {
            0 if i + 2 < t.len() => {
                pb.move_to(t[i + 1], t[i + 2]);
                i += 3;
            }
            1 if i + 2 < t.len() => {
                pb.line_to(t[i + 1], t[i + 2]);
                i += 3;
            }
            2 if i + 4 < t.len() => {
                pb.quad_to(t[i + 1], t[i + 2], t[i + 3], t[i + 4]);
                i += 5;
            }
            3 => {
                pb.close();
                i += 1;
            }
            _ => break,
        }
    }
    pb.finish()
}

